import { ComponentFixture, TestBed } from '@angular/core/testing';
import { Router } from '@angular/router';
import { NgZone } from '@angular/core';
import { HttpClientTestingModule } from '@angular/common/http/testing';
import { BehaviorSubject } from 'rxjs';
import { AppModule } from '../../app.module';
import { AppComponent } from '../../app.component';
import { ContextDesignerComponent } from './context-designer.component';
import { CatalogService } from '../../services/catalog.service';
import { ContextStore } from '../../services/context-store.service';
import { TokenService } from '../../services/token.service';
import { expandedFixture, supervisedFixture } from '../../../../tests/fixtures/contexts';
import { contextData } from '../../domain/serialize';
import { serializeYaml } from '../../domain/serialize';
import { BlueprintStore } from '../../services/blueprint-store.service';

const disconnected = { token$: new BehaviorSubject(''), status$: new BehaviorSubject('Disconnected'), hasToken: () => false };
describe('Designer browser workflow', () => {
  let fixture: ComponentFixture<ContextDesignerComponent>;
  beforeEach(async () => {
    await TestBed.configureTestingModule({ imports: [AppModule, HttpClientTestingModule], providers: [{ provide: TokenService, useValue: disconnected }] }).compileComponents();
    fixture = TestBed.createComponent(ContextDesignerComponent); fixture.detectChanges(); await fixture.whenStable();
  });
  afterEach(() => fixture.destroy());
  const change = async (fixture: ComponentFixture<any>, selector: string, value: string) => {
    const element = fixture.nativeElement.querySelector(selector) as HTMLInputElement;
    if (!element) throw new Error(`Missing field ${selector}`);
    element.value = value; element.dispatchEvent(new Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true }));
    fixture.detectChanges(); await fixture.whenStable(); fixture.detectChanges();
  };
  const click = async (fixture: ComponentFixture<any>, label: string) => {
    const button = Array.from(fixture.nativeElement.querySelectorAll('button') as NodeListOf<HTMLButtonElement>).find(b => b.textContent?.trim() === label);
    if (!button) throw new Error(`Missing button ${label}`);
    button.click(); fixture.detectChanges(); await fixture.whenStable(); fixture.detectChanges();
  };
  it('supplies a task descriptor, maps a reused alias, edits/cancels values, and reviews both exact exports', async () => {
    fixture.autoDetectChanges();
    const source = supervisedFixture();
    await click(fixture, 'Supply descriptor metadata');
    await change(fixture, '#metadata-json', '{broken'); await click(fixture, 'Save descriptor');
    expect(fixture.nativeElement.querySelector('dialog.metadata-dialog .error-box')).toBeTruthy();
    await change(fixture, '#metadata-json', JSON.stringify(source.task)); await click(fixture, 'Save descriptor');
    await change(fixture, '#task-selection', '91001@2'); await change(fixture, '#context-name', 'Browser fixture');
    const catalog = TestBed.inject(CatalogService);
    for (const entry of [...source.datasets, ...source.models, ...source.metrics]) catalog.upsert(entry.descriptor);
    fixture.componentInstance.setKind('dataset'); fixture.detectChanges();
    await change(fixture, '#catalog-selection', '92001@3'); await click(fixture, 'Configure dataset');
    await change(fixture, '#mapping-features', 'observations'); await change(fixture, '#mapping-labels', 'observations'); await click(fixture, 'Apply to draft');
    fixture.componentInstance.setKind('model'); fixture.detectChanges();
    await change(fixture, '#catalog-selection', '93001@1'); await click(fixture, 'Configure model'); await click(fixture, '+ Add explicit configuration'); await click(fixture, 'Apply to draft');
    fixture.componentInstance.setKind('metric'); fixture.detectChanges();
    await change(fixture, '#catalog-selection', '94001@1'); await click(fixture, 'Configure metric'); await click(fixture, 'Apply to draft');
    const store = TestBed.inject(ContextStore);
    fixture.componentInstance.edit(store.draft.models[0]); fixture.detectChanges();
    await click(fixture, '+ Add explicit configuration'); await click(fixture, 'Cancel');
    expect(store.draft.models[0].configurations.length).toBe(2);
    expect(fixture.componentInstance.blockers.length).toBe(0);
    await click(fixture, 'Review & export');
    const dialog = fixture.nativeElement.querySelector('.export-dialog') as HTMLDialogElement;
    expect(dialog.open).toBeTrue();
    expect((dialog.querySelector('#export-preview') as HTMLTextAreaElement).value).toContain('Task(module_id=91001, version=2)');
    await change(fixture, '#export-format', 'yaml');
    expect((dialog.querySelector('#export-preview') as HTMLTextAreaElement).value).toContain('"features":"observations","labels":"observations"');
    await click(fixture, 'Back to designer'); expect(dialog.open).toBeFalse();
    const changedTask = { ...source.task!, version: 3 }; catalog.upsert(changedTask); fixture.detectChanges();
    await change(fixture, '#task-selection', '91001@3');
    expect(store.draft.models.length).toBe(1); expect(fixture.componentInstance.blockers.some(i => i.path === 'models[1].task')).toBeTrue();
    expect(fixture.nativeElement.querySelectorAll('.model .component-node').length).toBe(1);
    await click(fixture, 'Review & export');
    const download = Array.from(dialog.querySelectorAll('button')).find(b => b.textContent?.includes('Download'))!;
    expect(download.disabled).toBeTrue(); await click(fixture, 'Back to designer');
  });
  it('switches task composition locally and preserves the recipe, blueprint, and display preference across routes', async () => {
    fixture.destroy();
    const store = TestBed.inject(ContextStore); store.draft = expandedFixture();
    const catalog = TestBed.inject(CatalogService);
    for (const entry of [...store.draft.datasets, ...store.draft.models, ...store.draft.metrics]) catalog.upsert(entry.descriptor);
    catalog.upsert(store.draft.task!);
    const root = TestBed.createComponent(AppComponent); root.detectChanges();
    const router = TestBed.inject(Router);
    await TestBed.inject(NgZone).run(() => router.navigateByUrl('/')); root.detectChanges(); await root.whenStable();
    expect(root.nativeElement.querySelector('.expansion').textContent).toContain('24');
    expect(root.nativeElement.querySelector('.canvas')).toBeNull();
    const data = contextData(store.draft);
    const toggle = root.nativeElement.querySelector('input[role="switch"]') as HTMLInputElement;
    expect(toggle.parentElement!.textContent).toContain('Show task composition');
    toggle.click(); root.detectChanges(); await root.whenStable();
    expect(root.nativeElement.querySelector('.canvas')).toBeTruthy();
    expect(root.nativeElement.textContent).toContain('estimated_labels');
    expect<unknown>(contextData(store.draft)).toEqual(data);
    const blueprintLink = root.nativeElement.querySelector('a[href="/node-editor"]') as HTMLAnchorElement;
    expect(blueprintLink.textContent).toContain('Blueprint');
    await TestBed.inject(NgZone).run(() => router.navigateByUrl('/node-editor')); root.detectChanges(); await root.whenStable();
    expect(root.nativeElement.querySelector('.blueprint-canvas')).toBeTruthy();
    expect(root.nativeElement.querySelectorAll('.blueprint-node').length).toBe(4);
    expect(root.nativeElement.querySelector('input[role="switch"]')).toBeNull();
    const blueprint = TestBed.inject(BlueprintStore);
    blueprint.nodes[0].x = 123;
    const addDataset = Array.from(root.nativeElement.querySelectorAll('.blueprint-toolbar button') as NodeListOf<HTMLButtonElement>).find(button => button.textContent?.trim() === 'Dataset')!;
    addDataset.click(); root.detectChanges(); await root.whenStable();
    const exportButton = Array.from(root.nativeElement.querySelectorAll('.page-heading button') as NodeListOf<HTMLButtonElement>).find(button => button.textContent?.includes('Review'))!;
    expect(exportButton.disabled).toBeTrue();
    await click(root, 'Choose component');
    await change(root, '#catalog-selection', '92001@3'); await click(root, 'Configure dataset');
    await change(root, '#mapping-features', 'observations'); await change(root, '#mapping-labels', 'observations');
    await click(root, 'Apply to draft');
    expect(store.draft.datasets.length).toBe(3);
    expect(blueprint.unconfiguredCount).toBe(0); expect(exportButton.disabled).toBeFalse();
    await click(root, 'Delete selected'); expect(store.draft.datasets.length).toBe(2);
    await TestBed.inject(NgZone).run(() => router.navigateByUrl('/')); root.detectChanges(); await root.whenStable();
    expect(store.draft.models[0].configurations.length).toBe(3);
    expect(root.nativeElement.querySelector('.expansion').textContent).toContain('24');
    expect(root.nativeElement.querySelector('.canvas')).toBeTruthy();
    expect(blueprint.nodes[0].x).toBe(123);
    root.destroy();
  });
  it('keeps mapping and parameter controls mounted across unrelated renders so editing stays responsive', async () => {
    const source = supervisedFixture();
    TestBed.inject(ContextStore).selectTask(source.task);
    fixture.componentInstance.edit(source.datasets[0]); fixture.detectChanges(); await fixture.whenStable();
    const mapping = fixture.nativeElement.querySelector('#mapping-features') as HTMLSelectElement;
    mapping.focus(); fixture.detectChanges();
    expect(fixture.nativeElement.querySelector('#mapping-features')).toBe(mapping);
    expect(document.activeElement).toBe(mapping);
    fixture.componentInstance.edit(source.models[0]); fixture.detectChanges(); await fixture.whenStable();
    const parameter = fixture.nativeElement.querySelector('input[inputmode="decimal"]') as HTMLInputElement;
    parameter.focus(); fixture.detectChanges();
    expect(fixture.nativeElement.querySelector('input[inputmode="decimal"]')).toBe(parameter);
    expect(document.activeElement).toBe(parameter);
  });
  it('previews an existing context, preserves current work on cancel/failure, and replaces all fields only when opened', async () => {
    const store = TestBed.inject(ContextStore), blueprint = TestBed.inject(BlueprintStore), catalog = TestBed.inject(CatalogService);
    store.draft = supervisedFixture(); store.draft.name = 'Keep this current draft';
    blueprint.add('processor', 10, 20);
    fixture.componentInstance.edit(store.draft.models[0]); fixture.detectChanges();
    await click(fixture, 'Open context');
    (fixture.nativeElement.querySelector('.paste-source summary') as HTMLElement).click();
    await change(fixture, '#context-document', 'type: context\nname: broken'); await click(fixture, 'Preview context');
    expect(fixture.nativeElement.querySelector('.open-context-dialog .error-box')).toBeTruthy();
    expect(store.draft.name).toBe('Keep this current draft'); expect(blueprint.nodes.length).toBe(1);
    const source = expandedFixture();
    for (const descriptor of [source.task!, ...source.datasets.map(e => e.descriptor), ...source.models.map(e => e.descriptor), ...source.metrics.map(e => e.descriptor)]) catalog.upsert(descriptor);
    await change(fixture, '#context-document', serializeYaml(source)); await click(fixture, 'Preview context');
    expect(fixture.nativeElement.querySelector('.context-preview').textContent).toContain('3 model configurations');
    await click(fixture, 'Cancel opening');
    expect(store.draft.name).toBe('Keep this current draft'); expect(fixture.componentInstance.editing).not.toBeNull();
    await click(fixture, 'Open context'); await click(fixture, 'Preview context');
    await click(fixture, 'Replace draft & open');
    expect<unknown>(contextData(store.draft)).toEqual(contextData(source));
    expect((fixture.nativeElement.querySelector('#context-name') as HTMLInputElement).value).toBe(source.name);
    expect((fixture.nativeElement.querySelector('#task-selection') as HTMLSelectElement).value).toBe('91001@2');
    expect(fixture.componentInstance.editing).toBeNull(); expect(blueprint.nodes.length).toBe(4);
    expect(blueprint.nodes.some(n => n.kind === 'processor')).toBeFalse(); expect(blueprint.edges.length).toBe(0);
    fixture.componentInstance.edit(store.draft.models[0]); fixture.detectChanges(); await fixture.whenStable();
    expect(fixture.nativeElement.querySelectorAll('.configuration').length).toBe(3);
    await click(fixture, 'Cancel'); await click(fixture, 'Review & export');
    expect((fixture.nativeElement.querySelector('#export-preview') as HTMLTextAreaElement).value).toContain('Task(module_id=91001, version=2)');
  });
  it('shows an imported task reference and editable saved settings even before catalog metadata arrives', async () => {
    const store = TestBed.inject(ContextStore), source = supervisedFixture();
    await click(fixture, 'Open context'); (fixture.nativeElement.querySelector('.paste-source summary') as HTMLElement).click();
    await change(fixture, '#context-document', serializeYaml(source)); await click(fixture, 'Preview context'); await click(fixture, 'Open in designer');
    const selectedTask = fixture.nativeElement.querySelector('#task-selection') as HTMLSelectElement;
    expect(selectedTask.value).toBe('91001@2'); expect(selectedTask.selectedOptions[0].textContent).toContain('saved reference');
    fixture.componentInstance.edit(store.draft.datasets[0]); fixture.detectChanges(); await fixture.whenStable();
    const savedAlias = fixture.nativeElement.querySelector('#saved-mapping-features') as HTMLInputElement;
    expect(savedAlias.value).toBe('observations');
    await change(fixture, '#saved-mapping-features', 'new-alias'); await click(fixture, 'Apply to draft');
    expect(store.draft.datasets[0].mapping['features']).toBe('new-alias');
    fixture.componentInstance.edit(store.draft.models[0]); fixture.detectChanges(); await fixture.whenStable();
    const savedSetting = fixture.nativeElement.querySelector('textarea[id^="saved-"]') as HTMLTextAreaElement;
    expect(savedSetting).toBeTruthy(); savedSetting.focus(); fixture.detectChanges();
    expect(document.activeElement).toBe(savedSetting);
    expect(fixture.componentInstance.blockers.some(issue => issue.severity === 'unknown')).toBeTrue();
  });
});
